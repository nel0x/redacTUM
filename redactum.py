#!/usr/bin/env python3
"""Optically cover the exam identifiers without removing underlying PDF data."""

import io
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import pdfplumber
from pypdf import PdfReader, PdfWriter
from reportlab.pdfgen import canvas


FULL_ID = re.compile(r"\d{4}-\d{2}-\d{4}-E\d{4}-\d{2}")
SHORT_ID = re.compile(r"\bE\d{4}\b")


def box(chars):
    return (
        min(c["x0"] for c in chars),
        min(c["top"] for c in chars),
        max(c["x1"] for c in chars),
        max(c["bottom"] for c in chars),
    )


def inside(inner, outer):
    return (
        inner[0] >= outer[0]
        and inner[1] >= outer[1]
        and inner[2] <= outer[2]
        and inner[3] <= outer[3]
    )


def page_boxes(page, first_page=False):
    boxes = []

    # Horizontal footer identifier.
    for hit in page.search(FULL_ID, regex=True, return_chars=True):
        boxes.append(box(hit["chars"]))

    # Rotated identifiers along the perforated outer edge.
    rotated = [c for c in page.chars if not c.get("upright", True)]
    rotated_text = "".join(c["text"] for c in rotated)
    for match in FULL_ID.finditer(rotated_text):
        boxes.append(box(rotated[match.start() : match.end()]))

    # The short booklet/pseudonym identifier in the sticker box on page 1.
    if first_page:
        for hit in page.search(SHORT_ID, regex=True, return_chars=True):
            candidate = box(hit["chars"])
            if not any(inside(candidate, full) for full in boxes):
                boxes.append(candidate)

    # Data-Matrix images in the top and bottom page corners only.
    for image in page.images:
        near_edge = image["x0"] < 110 or image["x1"] > page.width - 110
        near_corner = image["top"] < 70 or image["bottom"] > page.height - 40
        if near_edge and near_corner:
            boxes.append((image["x0"], image["top"], image["x1"], image["bottom"]))

    return boxes


def overlay(width, height, boxes, padding=1.0):
    data = io.BytesIO()
    c = canvas.Canvas(data, pagesize=(width, height))
    c.setFillColorRGB(0, 0, 0)
    for x0, top, x1, bottom in boxes:
        c.rect(
            x0 - padding,
            height - bottom - padding,
            x1 - x0 + 2 * padding,
            bottom - top + 2 * padding,
            stroke=0,
            fill=1,
        )
    c.save()
    data.seek(0)
    return PdfReader(data).pages[0]


def add_blackouts(source, target):
    reader = PdfReader(source)
    writer = PdfWriter()
    writer.clone_document_from_reader(reader)

    with pdfplumber.open(source) as layout:
        for index, page in enumerate(layout.pages):
            boxes = page_boxes(page, first_page=index == 0)
            writer.pages[index].merge_page(
                overlay(float(page.width), float(page.height), boxes), over=True
            )
            print(f"page {index + 1}: covered {len(boxes)} identifier regions")

    with open(target, "wb") as output:
        writer.write(output)


def rasterize(source, target, dpi=300):
    pdftoppm = shutil.which("pdftoppm")
    if not pdftoppm:
        raise SystemExit("pdftoppm is required (install Poppler first)")

    source_pages = PdfReader(source).pages
    with tempfile.TemporaryDirectory() as directory:
        directory = Path(directory)
        prefix = directory / "page"
        subprocess.run(
            [pdftoppm, "-png", "-r", str(dpi), source, str(prefix)],
            check=True,
        )
        images = sorted(directory.glob("page-*.png"))
        if len(images) != len(source_pages):
            raise RuntimeError("rendered page count does not match source PDF")

        image_pdf = directory / "image-only.pdf"
        first = source_pages[0]
        size = (float(first.mediabox.width), float(first.mediabox.height))
        c = canvas.Canvas(str(image_pdf), pagesize=size, pageCompression=1)
        c.setAuthor("")
        c.setCreator("")
        c.setTitle("")
        c.setSubject("")
        for page, image in zip(source_pages, images):
            width = float(page.mediabox.width)
            height = float(page.mediabox.height)
            c.setPageSize((width, height))
            c.drawImage(str(image), 0, 0, width, height, mask="auto")
            c.showPage()
        c.save()

        # Rewrite once more without the metadata generated by ReportLab.
        flattened = PdfReader(str(image_pdf))
        writer = PdfWriter()
        for page in flattened.pages:
            writer.add_page(page)
        writer.metadata = None
        with open(target, "wb") as output:
            writer.write(output)


def main(source, target, dpi=300):
    if Path(source).resolve() == Path(target).resolve():
        raise SystemExit("input and output must be different files")
    with tempfile.TemporaryDirectory() as directory:
        covered = str(Path(directory) / "covered.pdf")
        add_blackouts(source, covered)
        rasterize(covered, target, dpi=dpi)


if __name__ == "__main__":
    if len(sys.argv) not in (3, 4):
        raise SystemExit(f"usage: {sys.argv[0]} INPUT.pdf OUTPUT.pdf [DPI]")
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) == 4 else 300)
